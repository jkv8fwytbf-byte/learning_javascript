// Assignment operators set (or update) a variable's value.

let x = 10;

x = x + 5;
console.log("after x = x + 5:", x);

x += 5; // same as x = x + 5
console.log("after x += 5:", x);

x -= 3;
x *= 2;
x /= 4;
console.log("after -= *= /= :", x);

