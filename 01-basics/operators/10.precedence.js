// Operator precedence: * and / run before + and -.
// Use () when you want a different order.

console.log("2 + 3 * 4 =", 2 + 3 * 4); // 14, not 20
console.log("(2 + 3) * 4 =", (2 + 3) * 4); // 20

let x = (2 + 3) * 4;
console.log("x =", x);

