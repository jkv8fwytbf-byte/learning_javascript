// Ternary: short if/else that picks one of two values.
// condition ? valueIfTrue : valueIfFalse

const age = 20;
const message = age >= 18 ? "adult" : "minor";
console.log(message);

const points = 110;
const type = points > 100 ? "gold" : "silver";
console.log(type);

