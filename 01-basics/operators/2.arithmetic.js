// Arithmetic operators work with numbers.

let x = 10;
let y = 3;

console.log(x + y);
console.log(x - y);
console.log(x * y);
console.log(x / y);
console.log(x % y); // remainder
console.log(x ** y); // exponent (10^3)

// Increment / decrement
let z = 5;
console.log(z++); // uses z, then adds 1 → prints 5, z becomes 6
console.log(z);
console.log(++z); // adds 1 first → prints 7

